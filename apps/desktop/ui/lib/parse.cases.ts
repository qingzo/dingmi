import type { Repeat } from "./api";

export interface Want {
  title: string;
  due: string;
  repeat?: Partial<Repeat>;
  urgent?: boolean;
  /** 说明里应该有这段字 */
  detail?: string;
  /** 说得含糊：true 只看有没有，字符串就要一模一样 */
  guess?: true | string;
}

export interface Case {
  say: string;
  /** "YYYY-MM-DD HH:MM"，默认 2026-11-05 10:00 */
  now?: string;
  want: Want[];
  /** 拆出几条笔记，默认 0 */
  notes?: number;
  /** 同步过的电脑：[uid, 名字] */
  devices?: [string, string][];
  /** 只在这几台电脑上提醒 */
  only?: string[];
}

const r = (title: string, due: string, more: Omit<Want, "title" | "due"> = {}): Want => ({ title, due, ...more });
/** 一句话一条提醒 */
const c = (say: string, title: string, due: string, more: Omit<Want, "title" | "due"> = {}, opt: Partial<Case> = {}): Case => ({ say, want: [r(title, due, more)], ...opt });
/** 只有笔记，没有提醒 */
const noteOnly = (say: string): Case => ({ say, want: [], notes: 1 });
const on = (now: string) => ({ now });

const daily = { kind: "daily" } as const;
const weekdays = { kind: "weekdays" } as const;
const weekly = (...days: number[]) => ({ kind: "weekly" as const, days });
const biweekly = (...days: number[]) => ({ kind: "weekly" as const, days, every: 2 });
const monthly = (monthday: number) => ({ kind: "monthly" as const, monthday });
const interval = (every: number) => ({ kind: "interval" as const, every });
const yearly = (month: number, monthday: number) => ({ kind: "yearly" as const, month, monthday });
const monthLast = { kind: "month_last" } as const;
const monthNth = (nth: number, day: number) => ({ kind: "month_nth" as const, nth, days: [day] });
const lunar = (month: number, monthday: number) => ({ kind: "lunar_yearly" as const, month, monthday });
