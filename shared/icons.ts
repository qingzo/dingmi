export type IconName = keyof typeof ICONS;

const attrs = (a: Record<string, string | number>) => Object.entries(a).map(([k, v]) => ` ${k}="${v}"`).join("");

/** 一个图标的 SVG 文本；cls 加在 lucide 后面，比如 "s16" */
export function icon(name: IconName, cls = ""): string {
  const [, , children = []] = ICONS[name] as IconNode;
  const inner = children.map(([tag, a]) => `<${tag}${attrs(a)}/>`).join("");
  return `<svg class="lucide${cls ? ` ${cls}` : ""}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${inner}</svg>`;
}
